import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const result = await build({ entryPoints: ['workspace-ui/reader-source.js'], outfile: 'workspace-ui/reader.generated.js',
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true, metafile: true,
  legalComments: 'eof', banner: { js: '// Generated by scripts/build-workspace-reader.mjs. UI-only, pure Markdown and Lucide icons.' } });
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs).filter((p) => p.includes('node_modules/'))) {
  let directory = dirname(resolve(input));
  while (directory.includes('node_modules')) {
    try {
      const pkg = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
      if (pkg.name && pkg.version) { packages.set(pkg.name, { directory, version: pkg.version }); break; }
    } catch { /* find the owning package */ }
    directory = dirname(directory);
  }
}
const notices = [...packages].sort(([a], [b]) => a.localeCompare(b)).map(([name, { directory, version }]) => {
  for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENSE-MIT.txt', 'license', 'license.md']) {
    try { return `${name} ${version}\n${readFileSync(join(directory, file), 'utf8')}`; } catch { /* next spelling */ }
  }
  throw new Error(`Missing bundled dependency license: ${name}`);
});
writeFileSync('workspace-ui/reader-licenses.txt', notices.join('\n\n---\n\n'));
